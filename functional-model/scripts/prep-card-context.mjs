// Per-card scratch-folder builder for the FDN sink-only-synergy-model
// experiment's authoring pipeline (see the approved plan, Workstream 3, and
// `functional-model/ENGINE_DESIGN.md`/`SYNERGY_DESIGN.md` for the wider
// context) — given one FDN card, writes everything a later authoring agent
// needs into one gitignored scratch folder so authoring needs zero further
// tool calls (no live Forge/XMage/Scryfall lookups, no re-deriving the
// combinator vocabulary from the codebase by hand).
//
// STALE-PLAN CORRECTION (documented so this doesn't get re-litigated): the
// original plan wording said "fetch FDN Scryfall data into data/fdn/,
// mirror data/fin/'s layout" via some new fetch script. That's wrong as of
// this script's own authoring — `data/fin/fin_scryfall.json` was the OLD
// static-snapshot pattern `scripts/sync-card-db.mjs`'s own header comment
// explicitly replaced with a single committed SQLite bulk sync
// (`data/cards.db`) to stop tripping Scryfall's rate limit on cumulative
// per-set/per-card fetches. FDN's data is already in there — this script
// reads it straight out of `data/cards.db` (via `node:sqlite`'s
// `DatabaseSync`, same API `scripts/sync-card-db.mjs` already uses), scoped
// to `set_code = 'fdn'`. No new fetch script, no `data/fdn/` directory.
//
// Output location: `functional-model/.fdn-scratch/<slug>/` — deliberately
// OUTSIDE `functional-model/cards/` (unlike the plan's own suggested
// `functional-model/cards/<slug>/.scratch/`) because FDN cards don't have a
// `functional-model/cards/<fdn-slug>/` folder at all yet (that folder is
// created by the AUTHORING step, not this prep script), and several
// existing scripts (`card-status-batch.mjs`, `compute-card-status.mjs`,
// etc.) `readdir()` + dynamically `import()` EVERY entry under
// `functional-model/cards/` as if it were a card folder — a stray
// non-card scratch directory living there risks getting swept into that
// scan. Keeping it as a `functional-model/.fdn-scratch/` sibling avoids
// that risk entirely. Gitignored via a new `.gitignore` entry (see that
// file's own new comment block).
//
// Per-card slug: `word.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '')`
// — the SAME slugify already used by `scripts/review-card.mjs` et al., and
// verified against two real existing `functional-model/cards/` folder names
// before reuse here: "A Realm Reborn" -> `a-realm-reborn`, "Adventurer's
// Airship" -> `adventurer-s-airship` (apostrophe + the following run of
// non-alnum chars each collapse to their own single `-`). No FDN card is
// authored yet, so there is no established name<->slug table to consult —
// this keeps the FDN scratch folder's own name consistent with whatever
// name the eventual `functional-model/fdn-cards/<fdn-slug>/` folder will
// use (2026-09-18, later same day: FDN's own authored-card folder moved
// out of `functional-model/cards/` into this new sibling directory — see
// `functional-model/cards/README.md` — since FDN's own on-disk shape has
// almost nothing in common with FIN's; siblings step below now searches
// BOTH directories, see its own updated comment).
//
// Scratch folder contents (files omitted, never faked, when a source is
// genuinely absent — this script hard-fails instead when the FAILURE is
// its own, e.g. `data/cards.db` missing or the card not found at all; see
// "Fails loudly" below):
//   scryfall.json     - the card's raw Scryfall JSON (data/cards.db,
//                        set_code='fdn', is_normal DESC/released_at DESC
//                        picks the canonical printing — same convention
//                        `sync-card-db.mjs` documents on its own
//                        idx_cards_name_pick index).
//   forge.txt          - the real Forge cardsfolder script, via
//                        `forge-lookup.mjs`'s own `findForge` (imported,
//                        not re-implemented).
//   xmage.txt          - the real XMage card source, via the same script's
//                        `findXMage`, if found — secondary cross-check
//                        only, its absence is NOT an error.
//   siblings/*.ts       - 0-2 already-authored `definition.ts` files for
//                        OTHER cards whose Scryfall name also appears in
//                        the fdn set (i.e. genuine few-shot examples from
//                        the same target set) — empty today since no FDN
//                        card is authored yet; this fills in on its own,
//                        no script change needed, once the pipeline starts
//                        producing them.
//   effect-vocab.md     - the current `Effect` union (functional-model/
//                        card.ts) and combinator `ProgramNode` vocabulary
//                        (functional-model/combinator.ts) — every kind,
//                        field, supporting type, and builder-function
//                        signature, generated by parsing those two files'
//                        REAL current source with the TypeScript compiler
//                        API (not a hand-maintained list) so it can never
//                        silently drift stale.
//   NOTES.md            - resolved identity (name/slug/set/collector
//                        number) + a found/not-found line per source above,
//                        so the authoring agent doesn't have to guess why
//                        a file is missing.
//
// Fails loudly (throws, non-zero exit) rather than silently proceeding
// when: `data/cards.db` doesn't exist, or no fdn-set row matches the given
// slug/name at all. A missing Forge/XMage/sibling source is NOT one of
// these cases (real, expected, noted in NOTES.md, never an error) — that
// capacity-gap/red-style judgment is explicitly a LATER workstream's
// concern (Workstream 4), not this prep step's.
//
// Usage: npx vite-node functional-model/scripts/prep-card-context.mjs "<slug-or-name>"
//   npx vite-node functional-model/scripts/prep-card-context.mjs "abrade"
//   npx vite-node functional-model/scripts/prep-card-context.mjs "Ajani's Pridemate"
// (vite-node, not tsx, because the "siblings" step dynamically imports
// other cards' own `definition.ts` files — the same `.ts`-under-a-plain-
// runtime situation `compute-card-status.mjs`/`card-status-batch.mjs`
// already solved by running under vite-node; see `compute-one-card-
// status.mjs`'s own header comment for why a bare Nitro/node import of a
// sibling `.ts` from a `.mjs` script doesn't reliably work here.)

import { DatabaseSync } from 'node:sqlite';
import ts from 'typescript';
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { findForge, findXMage } from './forge-lookup.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..', '..');
const DB_PATH = join(ROOT, 'data', 'cards.db');
const CARD_TS = join(ROOT, 'functional-model', 'card.ts');
const COMBINATOR_TS = join(ROOT, 'functional-model', 'combinator.ts');
// Both are searched for siblings (2026-09-18, later same day): FIN's own
// pool (`cards/`, reference-only now — see `functional-model/cards/
// README.md` — same-name reprints still count as real few-shot examples,
// per this session's own explicit ruling: "if we already have a
// definition for a card reprint, we want to use it even if it's not from
// the same set") AND FDN's own dedicated authoring directory
// (`fdn-cards/`, so future FDN cards get real FDN-set siblings too, once
// more than these first 10 exist).
const CARDS_DIR = join(ROOT, 'functional-model', 'cards');
const FDN_CARDS_DIR = join(ROOT, 'functional-model', 'fdn-cards');
const SCRATCH_ROOT = join(ROOT, 'functional-model', '.fdn-scratch');

function slugify(word) {
  return word.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
}

// ---------------------------------------------------------------------------
// Step 1: resolve the argv slug-or-name to a real fdn-set Scryfall row.

function resolveCard(db, slugOrName) {
  const rows = db.prepare("SELECT * FROM cards WHERE set_code = 'fdn'").all();
  if (rows.length === 0) {
    throw new Error(`data/cards.db has zero rows with set_code='fdn' — is the DB stale/not synced? Run: node scripts/sync-card-db.mjs`);
  }
  const byName = new Map();
  for (const r of rows) {
    if (!byName.has(r.name)) byName.set(r.name, []);
    byName.get(r.name).push(r);
  }
  let name = [...byName.keys()].find((n) => n.toLowerCase() === slugOrName.toLowerCase());
  if (!name) name = [...byName.keys()].find((n) => slugify(n) === slugOrName);
  if (!name) {
    throw new Error(
      `No fdn-set card matches "${slugOrName}" by exact name OR by slug. Checked ${byName.size} distinct fdn names. ` +
        `Not a capacity gap — this is a hard prep-script failure (bad slug/typo/wrong set), not something to paper over.`
    );
  }
  const candidates = byName.get(name).slice().sort((a, b) => b.is_normal - a.is_normal || (b.released_at > a.released_at ? 1 : -1));
  const chosen = candidates[0];
  return { name, slug: slugify(name), row: chosen, raw: JSON.parse(chosen.raw_json) };
}

// ---------------------------------------------------------------------------
// Step 2: Forge/XMage source, via forge-lookup.mjs's own real lookup logic.

function forgeAndXmageText(name) {
  const forge = findForge(name);
  const xmage = findXMage(name);
  return {
    forgeText: forge.found ? `# ${forge.file}\n\n${forge.text}` : null,
    forgeNote: forge.found ? `found (${forge.file})` : forge.message,
    xmageText: xmage.found ? `# ${xmage.file}\n\n${xmage.text}` : null,
    xmageNote: xmage.found ? `found (${xmage.file})` : xmage.message,
  };
}

// ---------------------------------------------------------------------------
// Step 3: 0-2 sibling definition.ts files already authored for OTHER cards
// whose name also appears in the fdn set (genuine same-target-set few-shot
// examples). Searches BOTH `functional-model/cards/` (FIN's own
// reference-only pool — a same-name reprint there still counts, per this
// session's own explicit ruling) AND `functional-model/fdn-cards/` (FDN's
// own dedicated authoring directory, 2026-09-18 — none existed at all when
// this step was first written, so this dir is what actually starts
// producing real matches now that 10 real cards live there).

async function siblingCandidateDirs() {
  const out = [];
  for (const dir of [CARDS_DIR, FDN_CARDS_DIR]) {
    let entries;
    try {
      entries = readdirSync(dir, { withFileTypes: true }).filter((e) => e.isDirectory());
    } catch {
      continue;
    }
    for (const entry of entries) out.push({ dir, name: entry.name });
  }
  return out;
}

async function findFdnSiblings(db, excludeName, max = 2) {
  const candidates = await siblingCandidateDirs();
  const fdnNameCheck = db.prepare("SELECT 1 FROM cards WHERE set_code = 'fdn' AND name = ? LIMIT 1");
  const siblings = [];
  for (const { dir, name: entryName } of candidates) {
    if (siblings.length >= max) break;
    const defPath = join(dir, entryName, 'definition.ts');
    let mod;
    try {
      mod = await import(new URL(`file://${defPath}`).href);
    } catch {
      continue; // not a real card folder / import error — not this script's concern
    }
    const def = Object.values(mod)[0];
    if (!def?.name || def.name === excludeName) continue;
    if (!fdnNameCheck.get(def.name)) continue; // only "also in fdn" siblings count
    siblings.push({ slug: entryName, name: def.name, source: readFileSync(defPath, 'utf8') });
  }
  return siblings;
}

// ---------------------------------------------------------------------------
// Step 4: Effect/combinator vocabulary reference, derived from the REAL
// current card.ts/combinator.ts source via the TypeScript compiler API —
// never a hand-maintained snapshot, so it can't silently drift stale.

/** Generic printer: object-literal type -> `{ field: type; field2?: type2 }`,
 * union type -> `A | B | C`, anything else -> raw source text. Comments are
 * never included (leaf `.getText()` slices are comment-free by construction
 * for these node kinds) — kept deliberately compact, not a full doc dump. */
function printType(node, sf) {
  if (!node) return 'unknown';
  if (ts.isTypeLiteralNode(node)) {
    const fields = node.members.map((m) => {
      const name = m.name ? m.name.getText(sf) : '?';
      const optional = m.questionToken ? '?' : '';
      const typeText = m.type ? printType(m.type, sf) : 'unknown';
      return `${name}${optional}: ${typeText}`;
    });
    return `{ ${fields.join('; ')} }`;
  }
  if (ts.isUnionTypeNode(node)) {
    return node.types.map((t) => printType(t, sf)).join(' | ');
  }
  return node.getText(sf);
}

function firstSentence(text) {
  if (!text) return '';
  const cleaned = text
    .replace(/\/\*\*|\*\//g, '')
    .split('\n')
    .map((l) => l.replace(/^\s*\*\s?/, '').replace(/^\s*\/\/\s?/, ''))
    .join(' ')
    .replace(/\s+/g, ' ')
    .trim();
  const match = cleaned.match(/^.*?[.!?](?=\s|$)/);
  return (match ? match[0] : cleaned).slice(0, 240);
}

function leadingComment(node, sf) {
  const ranges = ts.getLeadingCommentRanges(sf.text, node.getFullStart()) ?? [];
  const text = ranges.map((r) => sf.text.slice(r.pos, r.end)).join('\n');
  return firstSentence(text);
}

function parseSourceFile(path) {
  const text = readFileSync(path, 'utf8');
  return { sf: ts.createSourceFile(path, text, ts.ScriptTarget.Latest, true), text };
}

/** Every `kind: '<literal>'`-discriminated variant of a union type alias
 * (e.g. card.ts's `Effect`, combinator.ts's `EachAction`/`ValueRef`/etc.)
 * whose variants are inline object-literal types. */
function describeInlineKindUnion(sf, aliasName) {
  let alias;
  ts.forEachChild(sf, (node) => {
    if (ts.isTypeAliasDeclaration(node) && node.name.text === aliasName) alias = node;
  });
  if (!alias || !ts.isUnionTypeNode(alias.type)) return [];
  return alias.type.types
    .filter((m) => ts.isTypeLiteralNode(m))
    .map((member) => {
      const kindProp = member.members.find((m) => m.name?.getText(sf) === 'kind');
      const kind = kindProp?.type ? kindProp.type.getText(sf).replace(/'/g, '') : '(no kind field)';
      const otherFields = member.members
        .filter((m) => m !== kindProp)
        .map((m) => `${m.name.getText(sf)}${m.questionToken ? '?' : ''}: ${m.type ? printType(m.type, sf) : 'unknown'}`);
      return { kind, fields: otherFields, doc: leadingComment(member, sf) };
    });
}

/** `export interface X { ... }` -> { name, fields, doc }. */
function describeInterface(sf, name) {
  let decl;
  ts.forEachChild(sf, (node) => {
    if (ts.isInterfaceDeclaration(node) && node.name.text === name) decl = node;
  });
  if (!decl) return null;
  const fields = decl.members.map((m) => `${m.name.getText(sf)}${m.questionToken ? '?' : ''}: ${m.type ? printType(m.type, sf) : 'unknown'}`);
  return { name, fields, doc: leadingComment(decl, sf) };
}

/** Plain `export type X = ...` alias (union of string literals, or a union
 * of type references to other named interfaces) -> raw printed type text. */
function describeTypeAlias(sf, name) {
  let decl;
  ts.forEachChild(sf, (node) => {
    if (ts.isTypeAliasDeclaration(node) && node.name.text === name) decl = node;
  });
  if (!decl) return null;
  return { name, text: printType(decl.type, sf), doc: leadingComment(decl, sf) };
}

/** `export function foo(a: T, b?: U): R { ... }` -> signature text only
 * (body dropped), plus a one-line doc summary. */
function describeFunctions(sf) {
  const out = [];
  ts.forEachChild(sf, (node) => {
    if (!ts.isFunctionDeclaration(node) || !node.name) return;
    const isExported = node.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword);
    if (!isExported) return;
    const params = node.parameters.map((p) => `${p.name.getText(sf)}${p.questionToken ? '?' : ''}: ${p.type ? printType(p.type, sf) : 'unknown'}`);
    const returnType = node.type ? printType(node.type, sf) : 'unknown';
    out.push({ name: node.name.text, signature: `${node.name.text}(${params.join(', ')}): ${returnType}`, doc: leadingComment(node, sf) });
  });
  return out;
}

function buildVocabReference() {
  const { sf: cardSf } = parseSourceFile(CARD_TS);
  const { sf: combSf } = parseSourceFile(COMBINATOR_TS);

  const effectVariants = describeInlineKindUnion(cardSf, 'Effect');

  const programNodeInterfaces = ['Each', 'Branch', 'Sequence', 'SelectUpTo', 'ApplyToBound', 'DrawCard']
    .map((n) => describeInterface(combSf, n))
    .filter(Boolean);
  const supportingInterfaces = ['Query', 'BoundSet', 'Filter', 'Aggregate', 'AddValue', 'BoundRef', 'CompareCondition', 'HasSubtypeCondition']
    .map((n) => describeInterface(combSf, n))
    .filter(Boolean);
  const supportingAliases = ['CardTypeWord', 'FilterPredicate', 'ValueRef', 'EachAction', 'CompareOp', 'Condition', 'SequenceStep', 'ProgramNode']
    .map((n) => describeTypeAlias(combSf, n))
    .filter(Boolean);
  const builderFunctions = describeFunctions(combSf).filter((f) => f.name !== 'runProgram' && f.name !== 'walkProgram');

  const lines = [];
  lines.push('# Effect / combinator vocabulary reference');
  lines.push('');
  lines.push(
    `Auto-generated by \`functional-model/scripts/prep-card-context.mjs\` by parsing the REAL current ` +
      `\`functional-model/card.ts\` (Effect union) and \`functional-model/combinator.ts\` (combinator DSL) ` +
      `source with the TypeScript compiler API — not a hand-maintained list. Regenerate by rerunning this ` +
      `script; never hand-edit this file.`
  );
  lines.push('');
  lines.push('## Effect union (`functional-model/card.ts`) — every `kind` a plain (non-program) Effect can use');
  lines.push('');
  lines.push("Per the project's combinator-DSL-is-default convention, prefer `kind:'program'` (below) for any");
  lines.push("new custom-effect logic over `kind:'custom'` closures — flag hard cases loudly instead of");
  lines.push('reaching for `custom`.');
  lines.push('');
  for (const v of effectVariants) {
    lines.push(`### \`${v.kind}\``);
    if (v.doc) lines.push(`> ${v.doc}`);
    if (v.fields.length) lines.push('```\n' + v.fields.join('\n') + '\n```');
    else lines.push('_(no fields beyond `kind`)_');
    lines.push('');
  }

  lines.push('## Combinator `program` vocabulary (`functional-model/combinator.ts`)');
  lines.push('');
  lines.push(
    "A `kind:'program'` Effect's own `program` field is one `ProgramNode` — build it with the builder " +
      'functions below (real cards use these, not raw AST object literals — see e.g. ' +
      '`functional-model/cards/beatrix-loyal-general/definition.ts`).'
  );
  lines.push('');
  lines.push('### `ProgramNode` variants');
  lines.push('');
  for (const i of programNodeInterfaces) {
    lines.push(`#### \`${i.name}\` (kind: \`${(i.fields.find((f) => f.startsWith('kind:')) ?? '').replace('kind: ', '') || i.name.toLowerCase()}\`)`);
    if (i.doc) lines.push(`> ${i.doc}`);
    lines.push('```\n' + i.fields.join('\n') + '\n```');
    lines.push('');
  }
  lines.push('### Supporting types');
  lines.push('');
  for (const i of supportingInterfaces) {
    lines.push(`#### \`${i.name}\``);
    if (i.doc) lines.push(`> ${i.doc}`);
    lines.push('```\n' + i.fields.join('\n') + '\n```');
    lines.push('');
  }
  for (const a of supportingAliases) {
    lines.push(`#### \`${a.name}\``);
    if (a.doc) lines.push(`> ${a.doc}`);
    lines.push('```\n' + a.text + '\n```');
    lines.push('');
  }
  lines.push('### Builder functions (the actual authoring API)');
  lines.push('');
  for (const f of builderFunctions) {
    lines.push(`- \`${f.signature}\`${f.doc ? ` — ${f.doc}` : ''}`);
  }
  lines.push('');
  lines.push(
    "Also exported: `you`/`opponents`/`anyPlayer`/`selfCard` query-root objects and the chainable " +
      '`QueryChain` class (`.filter(...)`, `.each(...)`, `.count()`, `.sum(field)`) — see `combinator.ts` ' +
      'itself if the builder-function signatures above aren\'t enough to express a query chain.'
  );

  return lines.join('\n');
}

// ---------------------------------------------------------------------------
// Main

async function main() {
  const slugOrName = process.argv[2];
  if (!slugOrName) {
    console.error('Usage: npx vite-node functional-model/scripts/prep-card-context.mjs "<slug-or-name>"');
    process.exit(1);
  }
  if (!existsSync(DB_PATH)) {
    throw new Error(`data/cards.db not found at ${DB_PATH} — run: node scripts/sync-card-db.mjs`);
  }

  const db = new DatabaseSync(DB_PATH);
  const { name, slug, row, raw } = resolveCard(db, slugOrName);
  const { forgeText, forgeNote, xmageText, xmageNote } = forgeAndXmageText(name);
  const siblings = await findFdnSiblings(db, name);
  db.close();

  const outDir = join(SCRATCH_ROOT, slug);
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });

  writeFileSync(join(outDir, 'scryfall.json'), JSON.stringify(raw, null, 2));
  writeFileSync(join(outDir, 'forge.txt'), forgeText ?? `(not found)\n\n${forgeNote}\n`);
  writeFileSync(join(outDir, 'xmage.txt'), xmageText ?? `(not found — secondary cross-check only, not blocking)\n\n${xmageNote}\n`);

  if (siblings.length) {
    mkdirSync(join(outDir, 'siblings'), { recursive: true });
    for (const s of siblings) writeFileSync(join(outDir, 'siblings', `${s.slug}.ts`), s.source);
  }

  writeFileSync(join(outDir, 'effect-vocab.md'), buildVocabReference());

  const notes = [
    `# ${name}`,
    '',
    `- slug: ${slug}`,
    `- set: fdn (collector_number ${row.collector_number}, scryfall_id ${row.scryfall_id})`,
    `- Forge source: ${forgeNote}`,
    `- XMage source: ${xmageNote}`,
    `- Sibling fdn definition.ts examples bundled: ${siblings.length ? siblings.map((s) => s.slug).join(', ') : 'none yet — no FDN card authored so far; this fills in automatically once some exist.'}`,
  ];
  writeFileSync(join(outDir, 'NOTES.md'), notes.join('\n') + '\n');

  console.log(`Wrote scratch context for "${name}" -> ${outDir}`);
  console.log(notes.join('\n'));
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
