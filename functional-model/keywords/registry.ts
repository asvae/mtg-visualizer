// Keyword/mechanic coverage suite registry — drives the "Keywords" page
// (app/pages/app/keywords/index.vue) and the server route that serves it
// (server/api/keywords/index.get.ts). An entry with `status: 'ai_reviewed'`
// or `'human_reviewed'` names a real engine-piloted bundle under
// functional-model/keywords/<bundle>/ (scenarios.ts + trace.json, generated
// by functional-model/scripts/run-keyword-scenarios.mjs) proving the engine
// genuinely implements that keyword/mechanic — real cards, no mocks, same
// discipline as functional-model/cards/<slug>. A `not_implemented` entry has
// no scenario at all — the keyword is recognized/cataloged here but nothing
// in engine.ts/state.ts/sba.ts (or, for many of these, nothing anywhere in
// this codebase at all) actually enforces it — listed anyway so the page is
// an honest, complete picture of the FULL historical MTG keyword taxonomy,
// not just of successes.
//
// NOT scanned by functional-model/scripts/verify-synergy.mjs or
// run-scenarios.mjs (both only ever walk functional-model/cards/) — this
// tree is entirely additive, no synergy.json of its own, no interaction
// with the per-card fact-matching pipeline.
//
// 2026-09-09: Expanded from a 15-entry FIN-only subset to the full
// historical MTG keyword taxonomy (369 entries) — see notes below on the
// 3 things that changed shape:
//
// (1) `status` is now 3-way, not binary: `'not_implemented'` (was `'gap'`),
// `'ai_reviewed'` (was `'covered'` — an AI-authored bundle+trace exists but
// nobody has human-confirmed it via the review workflow this status
// vocabulary is FOR yet), and `'human_reviewed'` (not yet used by any entry
// — reserved for the next pass once a human actually reviews one of these).
// All 15 originally-`covered` entries mapped straight to `ai_reviewed`;
// nothing was newly reviewed as part of this pass.
//
// (2) `category`'s `'fin-mechanic'` value is renamed `'set-specific'` — the
// taxonomy is no longer FIN-only, so "fin-mechanic" stopped being accurate
// (e.g. Ninjutsu, Cumulative upkeep, Convoke are real historical keywords
// with zero FIN presence, still correctly `'set-specific'` rather than
// `'evergreen'`). `card`/`ui` specialists: this is the one breaking rename
// in this field's own value space — the field NAME and its evergreen-first
// grouping semantics are unchanged.
//
// (3) New `setsUsed: string[]` field (Scryfall set codes, lowercase) on
// every `'set-specific'` entry — omitted for `'evergreen'` entries (those
// appear in nearly every set; the field would be uninformative there, and
// no entry currently sets it for an evergreen keyword).
// SOURCE + CAVEATS for setsUsed (read before trusting a specific list):
//   - Computed from `data/cards.db` (this repo's own local mirror of every
//     historical Scryfall PRINTING, ~109k rows, 1993-2027 — NOT the
//     oracle-cards bulk file, which dedupes by design and undercounts
//     early sets; see scripts/HISTORICAL_SETS_PROCESS.md's own data-file
//     notes for why). For each printing's own real `keywords` array (a
//     Scryfall-curated field — genuine keyword abilities/actions/ability
//     words, NOT a card's own one-off flavor-named abilities; Scryfall
//     tags those as "keywords" too on many joke/Universes-Beyond cards,
//     e.g. "The Goose is Loose" — excluded here by only counting a term
//     that ALSO appears in Scryfall's own public keyword-abilities/
//     keyword-actions/ability-words catalogs, see below), collected every
//     `set` code the term appears on.
//   - Filtered OUT `set_type: "promo"` and `"token"` printings (a promo
//     reprint duplicates an already-counted real product; a token print
//     isn't a spell/permanent a player casts). Every OTHER product type is
//     KEPT, including Commander-deck-only, Duel-deck-only, and Un-set
//     appearances — so a set code appearing here isn't always a
//     tournament-legal expansion; it's genuinely "printed somewhere with
//     this real term attached," which can be a long list for an old,
//     widely-reprinted keyword (Ward: ~80 codes). Left unfiltered further
//     — a UI concern (grouping/truncating for display) for `ui`/`card` to
//     decide, not a data-accuracy one.
//   - The taxonomy itself (which 371 terms exist at all, and whether each
//     is a "keyword ability"/"keyword action"/"ability word") is Scryfall's
//     own live public catalog endpoints (`/catalog/keyword-abilities`,
//     `/catalog/keyword-actions`, `/catalog/ability-words`), fetched fresh
//     2026-09-09 — 223 + 79 + 69 = 371 terms. This is the SAME source
//     WotC's own Comprehensive Rules glossary is built from, and it's kept
//     current by Scryfall as new sets release — more current than any
//     static list this comment could hardcode. `Saga` is deliberately NOT
//     one of the 371 (Scryfall doesn't tag it as a card `keyword` at all —
//     it's a card TYPE/subtype mechanic, not a keyword line) but this
//     file's own pre-existing `saga` entry stays, with its own `setsUsed`
//     now computed directly off real Saga-typed printings the same way
//     (`type_line` containing "Saga") for consistency.
//   - `ruleCite` for the ~354 entries newly added in this pass (everything
//     NOT already hand-verified before this expansion) is a deliberately
//     GENERIC citation ("CR 702 (keyword ability)" / "CR 701 (keyword
//     action)" / "CR 207.2c (ability word)") rather than a specific
//     numbered subsection — verifying all 354 individual CR subsection
//     numbers against a specific current rules build was out of scope for
//     this pass (subsection numbers DO shift over time as new keywords are
//     appended). The pre-existing hand-authored entries (Flying/Reach,
//     Menace, Hexproof, etc.) keep their own specific, previously-verified
//     citations, untouched.
//   - `gapNote` is populated ONLY where a term (a) is not yet
//     `ai_reviewed`/`human_reviewed` on this page AND (b) actually appears
//     on a real card in this pool (all 312 are FIN) — every such note below
//     was individually checked against this repo's own current
//     engine.ts/card.ts/state.ts/tokens.ts/ENGINE_DESIGN.md, not
//     auto-generated boilerplate; several (Equip, Crew, Fight, Surveil,
//     Mill) turn out to be genuinely well-supported already, just not
//     surfaced as a keywords/ bundle on this page yet — the note says so
//     explicitly rather than implying "engine gap" where there isn't one.
//     A term with NO real card in this pool gets no gapNote at all (not
//     fabricated) — the vast majority of the 354 newly-added entries are in
//     this "real historical keyword, zero FIN presence" bucket.
//   - Per this pass's own explicit scope: NO new engine implementation, no
//     new functional-model/keywords/<bundle> scenarios were built to
//     support this expansion — every non-FIN keyword (and every FIN
//     keyword lacking a pre-existing bundle) is `not_implemented` by
//     design, regardless of how "buildable" a gapNote's own research makes
//     it look. Scenario/bundle coverage stays exactly the pre-existing 15
//     entries' worth; this pass is registry data only.
//
// Follow-up (not built yet, flagged for the next pass): once a keyword's
// own bundle here is trusted, the "apply this proof to every card that
// carries the keyword" step would mean each `functional-model/cards/<slug>`
// with e.g. `keywords: ['Flying']` gets that fact attached automatically
// (a `sourceText`/`id` referencing this registry's own `key`, surfaced in
// its synergy.json some way) instead of every plain-vanilla-keyword card
// needing its own bespoke scenario — this file's `key`/`keywords` fields
// are shaped so a future script can look up "which registry entry covers
// keyword X" directly off `keywords`, but no such script exists yet.

export type KeywordStatus = 'not_implemented' | 'ai_reviewed' | 'human_reviewed';
export type KeywordCategory = 'evergreen' | 'set-specific';

export interface KeywordEntry {
  /** Stable id — used as this entry's own page anchor/URL slug. */
  key: string;
  /** Directory name under functional-model/keywords/ — only set for an `ai_reviewed`/`human_reviewed` entry (nothing to run otherwise). */
  bundle?: string;
  title: string;
  /**
   * Display/lookup identifiers for this entry. For the pre-existing,
   * bundle-backed entries these are real `Keyword` union members (card.ts)
   * — see that union's own doc comment. For an entry added in the
   * 2026-09-09 full-taxonomy expansion with no engine-side backing at all,
   * this is instead the plain Scryfall catalog display spelling (e.g.
   * "First strike" alias aside, most of these never had a card.ts
   * identifier to begin with) — deliberately NOT forced into card.ts's own
   * `Keyword` union, which stays scoped to "an identifier some real
   * CardDefinition/effect actually uses" per that union's own "extend as a
   * real card needs one" discipline (ENGINE_GAPS.md's same real-card-first
   * rule). This field itself stays plain `string[]`, not `Keyword[]` — no
   * compile-time coupling was ever added between this catalog and the
   * engine-internal type.
   */
  keywords: string[];
  /** Comprehensive Rules citation(s) this entry's own scenario/gap note is checked against — see this file's own header for which entries have a generic vs. specific citation. */
  ruleCite: string;
  /** Real card name(s) (Scryfall's own `name`) this entry demonstrates with, or (for a `not_implemented` entry) that actually carry this keyword in this pool. Empty when no real card in this pool (all 312 are FIN) carries it at all. */
  cardNames: string[];
  category: KeywordCategory;
  status: KeywordStatus;
  /** Populated only for a `not_implemented` entry that also has a non-empty `cardNames` — see this file's own header for the "don't fabricate" discipline. */
  gapNote?: string;
  /**
   * Scryfall set codes (lowercase) this keyword/mechanic has historically
   * appeared on, sourced from `data/cards.db` — see this file's own header
   * for the exact method and its caveats (promo/token prints excluded,
   * everything else kept; Saga computed off card TYPE instead of a
   * `keywords` tag). Only set for a `'set-specific'` entry; omitted for
   * `'evergreen'` (near-universal, uninformative). Can be an empty array
   * for a real catalog term with no printing in this local mirror at all
   * (a handful of the 371 — mostly generic keyword ACTIONS like "Tap"/
   * "Destroy" that Scryfall's own per-card `keywords` tagging never
   * actually applies to any single printing).
   */
  setsUsed?: string[];
}

