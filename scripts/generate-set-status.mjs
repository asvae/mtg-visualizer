// Regenerates SET_STATUS.md from tagging/card-enrichment-status.json, cross-
// referenced against each set's own raw Scryfall data (same in-scope filter as
// relations.test.mjs: drop basic lands and digital-only Alchemy rebalances).
//
// A set is "Human reviewed" only once every in-scope card has review "human"
// (enrichment doesn't have to be literally "human" too — FIN's live review loop
// always writes enrichment "ai"/review "human": a person confirmed AI-drafted
// tags, which is as good as this project's process ever produces). A set is
// "AI enriched" once every card has enrichment "ai" AND review "ai" (the full
// agent-vs-agent strict-review pass — see HISTORICAL_SETS_PROCESS.md step 8).
// Anything else is "Not started" (nothing touched) or "In progress" (mixed).
//
// Usage: node scripts/generate-set-status.mjs

import { readFile, readdir, writeFile } from 'node:fs/promises';

const STATUS_FILE = 'tagging/card-enrichment-status.json';
const OUT_FILE = 'SET_STATUS.md';

// Pretty names for known set codes; falls back to the raw code if not listed.
const SET_NAMES = {
  fin: 'Final Fantasy (FIN)',
  lea: 'Limited Edition Alpha (LEA)',
  leb: 'Limited Edition Beta (LEB)',
  '2ed': 'Unlimited Edition (2ED)',
  arn: 'Arabian Nights (ARN)',
  atq: 'Antiquities (ATQ)',
};

async function discoverSets() {
  const sets = [{ code: 'fin', dir: 'data/fin' }];
  for (const entry of await readdir('tagging/sets', { withFileTypes: true })) {
    if (entry.isDirectory()) sets.push({ code: entry.name, dir: `tagging/sets/${entry.name}` });
  }
  return sets;
}

async function inScopeCardNames(code, dir) {
  const raw = JSON.parse(await readFile(`${dir}/${code}_scryfall.json`, 'utf8'));
  const inScope = raw.filter((c) => !(c.type_line || '').includes('Basic') && !c.digital);

  // `name` is the project's storage key everywhere (relations files,
  // card-enrichment-status.json), on the assumption that it's 1:1 with
  // Scryfall's own `oracle_id` (the actual "same card design" identity —
  // stable across reprints/art variants, distinct for any genuinely
  // different design). That assumption holds for every set checked so far,
  // but assert it here instead of trusting it blindly: two rows sharing a
  // name but NOT sharing an oracle_id would be two different card designs
  // silently collapsed into one relations entry, losing one of them.
  const nameToOracle = new Map();
  for (const c of inScope) {
    const prev = nameToOracle.get(c.name);
    if (prev !== undefined && prev !== c.oracle_id) {
      throw new Error(
        `${code}: "${c.name}" maps to multiple oracle_ids (${prev}, ${c.oracle_id}) — ` +
          `these are two different card designs sharing a name, not reprints. ` +
          `Dedup-by-name would silently lose one; needs manual handling.`,
      );
    }
    nameToOracle.set(c.name, c.oracle_id);
  }
  // Dedupe by name (multiple art/printing variants of the same design count
  // once) — matches how every other count in this pipeline is reported. Some
  // raw files (e.g. arn_scryfall.json) aren't pre-deduplicated themselves.
  return [...nameToOracle.keys()];
}

function classify(cards) {
  if (cards.every((c) => c.review === 'human')) return 'Human reviewed (complete)';
  if (cards.every((c) => c.enrichment === 'ai' && c.review === 'ai')) return 'AI enriched (complete)';
  if (cards.every((c) => c.enrichment === 'none')) return 'Not started';
  return 'In progress';
}

function tally(cards, key) {
  const counts = {};
  for (const c of cards) counts[c[key]] = (counts[c[key]] || 0) + 1;
  return Object.entries(counts)
    .sort((a, b) => b[1] - a[1])
    .map(([value, n]) => `${value}: ${n}`)
    .join(', ');
}

async function main() {
  const status = JSON.parse(await readFile(STATUS_FILE, 'utf8'));
  const sets = await discoverSets();

  const rows = [];
  for (const { code, dir } of sets) {
    let names;
    try {
      names = await inScopeCardNames(code, dir);
    } catch {
      continue; // no scryfall data for this set yet
    }
    const cards = names.map((name) => status[name] ?? { enrichment: 'none', review: 'none' });
    rows.push({
      code,
      name: SET_NAMES[code] ?? code.toUpperCase(),
      total: cards.length,
      label: classify(cards),
      enrichment: tally(cards, 'enrichment'),
      review: tally(cards, 'review'),
    });
  }

  const lines = [
    '# Set status',
    '',
    `Generated by \`scripts/generate-set-status.mjs\` from \`${STATUS_FILE}\` — do not`,
    'hand-edit, rerun the script instead (\`npm run set-status\`).',
    '',
    '"Human reviewed" = every in-scope card has `review: "human"`. "AI enriched" =',
    'every card has `enrichment: "ai"` AND `review: "ai"` (finished the full',
    'agent-vs-agent strict-review pass). See `scripts/GLOBAL_TAGGING_RULES.md`\'s',
    '"Output shape" section for what the two axes mean.',
    '',
    `Generated: ${new Date().toISOString().slice(0, 10)}`,
    '',
    '| Set | Cards | Status | Enrichment | Review |',
    '|---|---|---|---|---|',
    ...rows.map(
      (r) => `| ${r.name} | ${r.total} | ${r.label} | ${r.enrichment} | ${r.review} |`,
    ),
  ];

  await writeFile(OUT_FILE, lines.join('\n') + '\n');
  console.log(`Wrote ${OUT_FILE} (${rows.length} sets)`);
}

main();
